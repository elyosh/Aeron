/*
 * brdf_lut_gen — writes the split-sum BRDF table used by the PBR shaders.
 *
 * The scene renderer used to compute this table the first time it set up
 * PBR rendering, which took about 20 ms. The result depends only on the
 * table size and the sample count, so it is now generated once and checked
 * in as aeron/src/scene/brdf_lut.inc.
 *
 * Differences between math libraries disappear when the values are stored
 * as half floats, but fused multiply-add changes a few of them by one unit
 * in the last place. The tool is built without it (see CMakeLists.txt), so
 * every machine produces the same file.
 *
 * Usage: brdf_lut_gen <output.inc>
 * Run it again after changing the table size, the sample count or the
 * integration below.
 */

#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define BRDF_LUT_SIZE 64
#define BRDF_LUT_SAMPLES 512

static uint16_t brdf_float_to_half(float value) {
	uint32_t bits;
	memcpy(&bits, &value, sizeof bits);
	const uint32_t sign     = (bits >> 16) & 0x8000u;
	const int32_t  exponent = (int32_t)((bits >> 23) & 0xFFu) - 127 + 15;
	uint32_t       mantissa = bits & 0x7FFFFFu;
	if (exponent <= 0) {
		if (exponent < -10)
			return (uint16_t)sign;
		mantissa |= 0x800000u;
		const uint32_t shift = (uint32_t)(14 - exponent);
		return (uint16_t)(sign | ((mantissa + (1u << (shift - 1u))) >> shift));
	}
	if (exponent >= 31)
		return (uint16_t)(sign | 0x7C00u);
	uint32_t half = sign | ((uint32_t)exponent << 10) | (mantissa >> 13);
	if (mantissa & 0x1000u)
		++half; /* round half up; ample for a lookup table */
	return (uint16_t)half;
}

static float brdf_radical_inverse(uint32_t bits) {
	bits = (bits << 16u) | (bits >> 16u);
	bits = ((bits & 0x55555555u) << 1u) | ((bits & 0xAAAAAAAAu) >> 1u);
	bits = ((bits & 0x33333333u) << 2u) | ((bits & 0xCCCCCCCCu) >> 2u);
	bits = ((bits & 0x0F0F0F0Fu) << 4u) | ((bits & 0xF0F0F0F0u) >> 4u);
	bits = ((bits & 0x00FF00FFu) << 8u) | ((bits & 0xFF00FF00u) >> 8u);
	return (float)bits * 2.3283064365386963e-10f;
}

/* Split-sum integration (Karis 2013): GGX importance samples with N = +Z,
 * Smith-Schlick visibility with the image-based k = alpha / 2. */
static void brdf_integrate(float ndotv, float roughness, float* out_a, float* out_b) {
	const float alpha = roughness * roughness;
	const float k     = alpha * 0.5f;
	const float v[3]  = { sqrtf(1.0f - ndotv * ndotv), 0.0f, ndotv };
	double      a = 0.0, b = 0.0;
	for (uint32_t i = 0; i < BRDF_LUT_SAMPLES; ++i) {
		const float u1        = ((float)i + 0.5f) / (float)BRDF_LUT_SAMPLES;
		const float u2        = brdf_radical_inverse(i);
		const float phi       = 6.28318530718f * u2;
		const float cos_theta = sqrtf((1.0f - u1) / (1.0f + (alpha * alpha - 1.0f) * u1));
		const float sin_theta = sqrtf(1.0f - cos_theta * cos_theta);
		const float h[3]      = { sin_theta * cosf(phi), sin_theta * sinf(phi), cos_theta };
		const float vdoth     = v[0] * h[0] + v[1] * h[1] + v[2] * h[2];
		const float l_z       = 2.0f * vdoth * h[2] - v[2];
		if (l_z <= 0.0f || vdoth <= 0.0f)
			continue;
		const float g_v = ndotv / (ndotv * (1.0f - k) + k);
		const float g_l = l_z / (l_z * (1.0f - k) + k);
		const float vis = g_v * g_l * vdoth / (h[2] * ndotv);
		const float fc  = powf(1.0f - vdoth, 5.0f);
		a += (double)((1.0f - fc) * vis);
		b += (double)(fc * vis);
	}
	*out_a = (float)(a / BRDF_LUT_SAMPLES);
	*out_b = (float)(b / BRDF_LUT_SAMPLES);
}

int main(int argc, char** argv) {
	static uint16_t texels[BRDF_LUT_SIZE * BRDF_LUT_SIZE * 2];
	if (argc != 2) {
		fprintf(stderr, "usage: %s <output.inc>\n", argv[0]);
		return 2;
	}
	/* Rows are roughness and columns are N.V, both sampled at texel centres. */
	for (int y = 0; y < BRDF_LUT_SIZE; ++y) {
		const float roughness = ((float)y + 0.5f) / (float)BRDF_LUT_SIZE;
		for (int x = 0; x < BRDF_LUT_SIZE; ++x) {
			const float ndotv = ((float)x + 0.5f) / (float)BRDF_LUT_SIZE;
			float       a, b;
			brdf_integrate(ndotv, roughness, &a, &b);
			texels[(y * BRDF_LUT_SIZE + x) * 2 + 0] = brdf_float_to_half(a);
			texels[(y * BRDF_LUT_SIZE + x) * 2 + 1] = brdf_float_to_half(b);
		}
	}

	FILE* out = fopen(argv[1], "w");
	if (!out) {
		fprintf(stderr, "%s: cannot write %s\n", argv[0], argv[1]);
		return 1;
	}
	fprintf(out,
			"/* Generated by aeron/tools/brdf_lut_gen - do not edit.\n"
			" * Split-sum BRDF table: %d x %d texels, %d samples per texel. Each texel\n"
			" * holds two half floats (A, B); rows are roughness and columns are N.V. */\n"
			"\n"
			"#define AERON_BRDF_LUT_SIZE %d\n"
			"\n"
			"static const uint16_t aeron_brdf_lut[%d] = {\n",
			BRDF_LUT_SIZE, BRDF_LUT_SIZE, BRDF_LUT_SAMPLES, BRDF_LUT_SIZE, BRDF_LUT_SIZE * BRDF_LUT_SIZE * 2);
	const int count = BRDF_LUT_SIZE * BRDF_LUT_SIZE * 2;
	for (int i = 0; i < count; ++i) {
		fprintf(out, "%s0x%04x,%s", i % 12 == 0 ? "\t" : "", texels[i],
				i % 12 == 11 || i == count - 1 ? "\n" : " ");
	}
	fprintf(out, "};\n");
	if (fclose(out) != 0) {
		fprintf(stderr, "%s: cannot write %s\n", argv[0], argv[1]);
		return 1;
	}
	return 0;
}
